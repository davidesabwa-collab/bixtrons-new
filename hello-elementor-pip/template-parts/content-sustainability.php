<h2 class="heading-dropshadow tile-heading">Environment</h2>
<div class="sa-copy">
<p>Addressing its environmental footprint and climate-related challenges is one the key priorities in PIP Global Safety's sustainability management. Our <a href="/images/sustainability/2025-PIP-Environmental-Policy.pdf" target="_blank">Environmental Policy</a> and <a href="/images/sustainability/PIP-Global-Safety-Supplier-Code-of-Conduct.pdf" target="_blank">Supplier Code of Conduct</a> set clear expectations for both our own operations and our suppliers to reduce greenhouse gas (GHG) emissions and advance lower-carbon practices across. In 2025, we completed our first GHG baseline covering PIP Global Safety's Scope 1, Scope 2 and select Scope 3 emissions based on the GHG Protocol. We also conducted a <a href="/images/sustainability/2025-PIP-Global-Safety-Climate-related-Risks-and-Opportunties-Report_SB-261.pdf" target="_blank">Climate Risk Assessment</a> aligned with international standards such as the European Sustainability Reporting Standards (ESRS) and California Climate Disclosures. Together, these assessments provide an initial evidence base foundation for identifying globally coordinated mitigation and adaptation measures. These steps mark the beginning of our journey to better understand and manage our environmental impacts, and strengthen our approach to climate resilience.</p>
