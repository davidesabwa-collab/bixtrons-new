<div class="container social-copy">
<h3>Our Employees:</h3>
<p>PIP Global Safety is committed to fostering fair, safe, and respectful working conditions for all employees. Guided by our Global Code of Conduct, we uphold equal treatment, compliance with labor laws, and protection against all forms of discrimination and harassment. Our policies and procedures are designed to promote workplace integrity and well-being, helping to create an environment in which employees feel supported and valued. Through accessible reporting channels, we strive to maintain a culture of mutual respect and dignity throughout our organization.</p>
</div>
</div>
<div class="item">
<div class="container social-copy">
<h3>Our Supply Chain:</h3>
<p>PIP Global Safety's sustainability approach extends to protecting human rights and labor standards across its supply chain. Based on our <a href="https://www.pipglobal.com/images/sustainability/PIP-Global-Safety-Supplier-Code-of-Conduct.pdf" target="_blank">Supplier Code of Conduct</a>, we ask suppliers to conduct proactive due diligence and take steps to support safe, healthy, fair, and inclusive working conditions, while upholding high standards of worker welfare and rights.</p>
<p>Our Code prohibits all forms of forced and child labor and mandates fair wages and safe working conditions. It also requires suppliers to implement grievance mechanisms and comply with international standards such as the UNGPs and ILO conventions. By strengthening supplier compliance and transparency, we aim to mitigate systemic labor risks in line with our commitment to human rights and labor standards.</p>
